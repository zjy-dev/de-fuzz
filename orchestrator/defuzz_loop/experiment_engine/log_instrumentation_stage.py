"""Deterministic source log-instrumentation off validated source mappings.

This stage sits between source mapping and the agent audit (methodology step 3:
"日志插桩"). It consumes the validated ``source-mappings.jsonl`` handoff, assigns
a unique ``<mechanism>#<uid>`` identity to every cited anchor (pass, target
functions, critical structs, and gate conditions), and emits a rebuild-ready
instrumentation of a disposable compiler-source copy:

* ``DEFUZZ_HIT("<mechanism>#<uid>:hit")`` runtime probes at safe critical-gate
  statement boundaries, so the feedback agent can later observe whether a
  mapped condition is actually reached at run time; and
* ``/* DEFUZZ-ANCHOR ... */`` annotation markers at every other anchor.

The probe is defined once per touched translation unit, right after its
``#include "system.h"`` (which transitively provides ``fprintf``/``getenv``),
and is gated on the ``DEFUZZ_LOG`` environment variable so an instrumented
compiler behaves identically to a stock build unless logging is enabled.

The stage performs no model calls. It writes the unified diff, a per-anchor
instrumentation plan, a log-id catalog, and a summary; the diff is applied to
the frozen compiler source and rebuilt by the separate recompile step.
"""

from __future__ import annotations

import difflib
import hashlib
import json
import re
import tempfile
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from ..audit_schema import normalize_mechanism
from .models import ArtifactRef, ExperimentPlan, StageResult
from .source_mapping_stage import load_source_mappings, sha256
from .workspace import WorkspaceBuilder

_ACTIVE_PROBE_SUFFIXES = (".cc", ".cpp", ".c", ".cxx")
_SYSTEM_H_RE = re.compile(r'^\s*#\s*include\s+"system\.h"')
_IF_RE = re.compile(r"^(?P<indent>\s*)if\s*\(")

_PROBE_BLOCK = (
    "/* DEFUZZ-LOG-PROBE (generated by log-instrumentation stage) */\n"
    "#ifndef DEFUZZ_LOG_PROBE_DEFINED\n"
    "#define DEFUZZ_LOG_PROBE_DEFINED 1\n"
    "static int defuzz_log_enabled (void)\n"
    "{\n"
    "  static int defuzz_log_state = -1;\n"
    "  if (defuzz_log_state < 0)\n"
    '    defuzz_log_state = getenv ("DEFUZZ_LOG") != 0;\n'
    "  return defuzz_log_state;\n"
    "}\n"
    "#define DEFUZZ_HIT(id) \\\n"
    "  do { if (defuzz_log_enabled ()) \\\n"
    '    fprintf (stderr, "[DEFUZZ_LOG] %s\\n", (id)); } while (0)\n'
    "#endif /* DEFUZZ_LOG_PROBE_DEFINED */\n"
)


def _uid(parts: Sequence[Any]) -> str:
    payload = "\x1f".join("" if value is None else str(value) for value in parts)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:12]


def _anchor_rows(mapping: Any) -> list[dict[str, Any]]:
    """Flatten one validated mapping into ordered anchor rows."""

    rows: list[dict[str, Any]] = []
    pass_anchor = mapping.level_1_pass
    rows.append({
        "kind": "pass", "name": pass_anchor.name, "file": pass_anchor.file,
        "line": pass_anchor.line_start, "detail": pass_anchor.evidence,
    })
    for fn in mapping.level_2_functions:
        rows.append({"kind": "function", "name": fn.name, "file": fn.file,
                     "line": fn.line, "detail": fn.role})
    for struct in mapping.level_3_critical_structs:
        rows.append({"kind": "struct", "name": struct.name, "file": struct.file,
                     "line": struct.line, "detail": struct.role})
    for cond in mapping.level_3_critical_conditions:
        rows.append({"kind": "condition", "name": cond.expression, "file": cond.file,
                     "line": cond.line, "detail": cond.role})
    return rows


def _safe_active_probe(lines: list[str], line_no: int) -> bool:
    """Only probe a gate when inserting a statement before it stays valid C/C++."""

    index = line_no - 1
    if not 0 <= index < len(lines):
        return False
    stripped = lines[index].strip()
    if not _IF_RE.match(lines[index]) or stripped.startswith("else"):
        return False
    for previous in range(index - 1, -1, -1):
        candidate = lines[previous].strip()
        if not candidate:
            continue
        # ``else``/``do``/label/control continuations make a leading statement
        # insertion unsafe; keep those anchors annotation-only.
        return not (candidate.endswith("else") or candidate.endswith("do")
                    or candidate.endswith(")") and candidate.startswith(("for", "while")))
    return True


def _instrument_file(
    original: str, rows: Sequence[dict[str, Any]],
) -> tuple[str, dict[str, bool]]:
    """Return instrumented text and {uid: active-probe?} for one file."""

    lines = original.splitlines(keepends=True)
    newline = "\n"
    if lines and not lines[-1].endswith(("\n", "\r")):
        lines[-1] = lines[-1] + newline
    bodies: dict[int, list[str]] = {}
    probe_mode: dict[str, bool] = {}
    needs_probe_block = False
    for row in rows:
        line_no = int(row["line"])
        index = line_no - 1
        indent = ""
        if 0 <= index < len(lines):
            indent = lines[index][: len(lines[index]) - len(lines[index].lstrip())]
        log_id = f'{row["log_id"]}:hit'
        active = (
            row["kind"] == "condition"
            and row["suffix"] in _ACTIVE_PROBE_SUFFIXES
            and row["has_system_h"]
            and _safe_active_probe(lines, line_no)
        )
        probe_mode[row["uid"]] = active
        if active:
            needs_probe_block = True
            bodies.setdefault(line_no, []).append(
                f'{indent}DEFUZZ_HIT ("{log_id}"); '
                f'/* DEFUZZ-ANCHOR {row["log_id"]}:{row["kind"]} '
                f'phi={row["phi_id"]} isa={row["isa"]} */{newline}'
            )
        else:
            bodies.setdefault(line_no, []).append(
                f'{indent}/* DEFUZZ-ANCHOR {row["log_id"]}:{row["kind"]} '
                f'phi={row["phi_id"]} isa={row["isa"]} */{newline}'
            )
    if needs_probe_block:
        system_line = next(
            (i + 1 for i, text in enumerate(lines) if _SYSTEM_H_RE.match(text)), None
        )
        if system_line is not None:
            block = [part + newline for part in _PROBE_BLOCK.splitlines()]
            bodies.setdefault(system_line + 1, [])
            bodies[system_line + 1] = block + bodies[system_line + 1]
    for line_no in sorted(bodies, reverse=True):
        index = max(0, min(line_no - 1, len(lines)))
        lines[index:index] = bodies[line_no]
    return "".join(lines), probe_mode


async def run(
    plan: ExperimentPlan | Mapping[str, Any], repetition: int, output_dir: Path,
    backend: Any | None = None,
) -> StageResult:
    del backend  # The stage is deterministic; it never calls a model.
    try:
        if not isinstance(plan, ExperimentPlan):
            plan = ExperimentPlan.model_validate(plan)
        params = plan.parameters
        raw_mappings = params.get("source_mappings")
        if not raw_mappings:
            raise ValueError("log-instrumentation requires validated source mappings")
        configured_root = params.get("source_root") or plan.source_root
        if not configured_root:
            raise ValueError("log-instrumentation requires an explicit compiler source root")
        root = Path(str(configured_root)).expanduser().resolve(strict=True)
        if not root.is_dir():
            raise ValueError("log-instrumentation requires a compiler source directory")
        mappings, summary = load_source_mappings(
            Path(str(raw_mappings)), source_root=root,
            expected_sha256=params.get("source_mappings_sha256"),
        )
        output_dir.mkdir(parents=True, exist_ok=True)

        # Flatten every anchor, assigning a stable unique log identity.
        by_file: dict[str, list[dict[str, Any]]] = {}
        plan_rows: list[dict[str, Any]] = []
        seen: set[str] = set()
        # The mechanism is carried on the accepted invariant, not on the mapping;
        # recover it from the frozen accepted-invariants artifact.
        mechanism_by_phi = _mechanism_by_phi(summary, params)
        for mapping in mappings:
            mechanism = mechanism_by_phi.get(mapping.phi_id, "unknown")
            for row in _anchor_rows(mapping):
                uid = _uid([mechanism, mapping.phi_id, mapping.isa, row["kind"],
                            row["file"], row["line"], row["name"]])
                if uid in seen:
                    uid = _uid([uid, len(seen)])
                seen.add(uid)
                suffix = Path(row["file"]).suffix.lower()
                record = {
                    "uid": uid, "log_id": f"{mechanism}#{uid}", "mechanism": mechanism,
                    "phi_id": mapping.phi_id, "isa": mapping.isa, "compiler": mapping.compiler,
                    "kind": row["kind"], "name": row["name"], "file": row["file"],
                    "line": row["line"], "role": row["detail"], "suffix": suffix,
                    "has_system_h": False,
                }
                by_file.setdefault(row["file"], []).append(record)
                plan_rows.append(record)

        # Materialize a disposable source copy and instrument it in place.
        failures: list[str] = []
        touched_files: list[dict[str, Any]] = []
        diff_chunks: list[str] = []
        active_count = 0
        with tempfile.TemporaryDirectory(prefix="defuzz-instrument-") as temporary:
            workspace = WorkspaceBuilder(root).materialize(Path(temporary) / "source")
            for rel, rows in sorted(by_file.items()):
                target = (workspace.root / rel).resolve()
                try:
                    target.relative_to(workspace.root.resolve())
                except ValueError:
                    failures.append(f"{rel}: anchor escapes the source workspace")
                    continue
                original = target.read_text(encoding="utf-8", errors="surrogatepass")
                has_system_h = any(_SYSTEM_H_RE.match(line) for line in original.splitlines())
                for record in rows:
                    record["has_system_h"] = has_system_h
                instrumented, probe_mode = _instrument_file(original, rows)
                for record in rows:
                    record["probe"] = "active" if probe_mode.get(record["uid"]) else "annotation"
                    active_count += int(record["probe"] == "active")
                if instrumented == original:
                    failures.append(f"{rel}: produced no instrumentation")
                    continue
                target.write_text(instrumented, encoding="utf-8", errors="surrogatepass")
                diff_chunks.extend(difflib.unified_diff(
                    original.splitlines(keepends=True),
                    instrumented.splitlines(keepends=True),
                    fromfile=f"a/{rel}", tofile=f"b/{rel}",
                ))
                touched_files.append({
                    "file": rel, "anchors": len(rows),
                    "before_sha256": hashlib.sha256(original.encode()).hexdigest(),
                    "after_sha256": hashlib.sha256(instrumented.encode()).hexdigest(),
                })

        diff_text = "".join(diff_chunks)
        diff_path = output_dir / "instrumentation.diff"
        diff_path.write_text(diff_text, encoding="utf-8")
        probe_header_path = output_dir / "defuzz-log-probes.txt"
        probe_header_path.write_text(_PROBE_BLOCK, encoding="utf-8")
        plan_path = output_dir / "instrumentation-plan.jsonl"
        _drop = {"suffix", "has_system_h"}
        plan_path.write_text(
            "".join(
                json.dumps({k: v for k, v in row.items() if k not in _drop}, sort_keys=True) + "\n"
                for row in plan_rows
            ),
            encoding="utf-8",
        )
        mechanisms = sorted({row["mechanism"] for row in plan_rows})
        isas = sorted({row["isa"] for row in plan_rows})
        catalog = {
            "schema_version": 1, "kind": "defuzz-log-id-catalog",
            "source_root": str(root), "source_tree_sha256": summary.get("source_tree_sha256"),
            "source_mappings_sha256": sha256(Path(str(raw_mappings))),
            "compiler": mappings[0].compiler if mappings else params.get("compiler"),
            "isas": isas, "mechanisms": mechanisms,
            "total_anchors": len(plan_rows), "active_probes": active_count,
            "annotations": len(plan_rows) - active_count,
            "touched_files": len(touched_files),
            "log_ids": sorted(f"{row['log_id']}:hit" for row in plan_rows),
        }
        catalog_path = output_dir / "log-id-catalog.json"
        catalog_path.write_text(json.dumps(catalog, indent=2, sort_keys=True) + "\n")

        status = "completed" if plan_rows and not failures else "failed"
        if not plan_rows:
            failures.append("no anchors to instrument from the source mapping handoff")
            status = "failed"
        summary_record = {
            "schema_version": 1, "stage": "log-instrumentation", "status": status,
            "repetition": repetition, "source_root": str(root),
            "source_tree_sha256": summary.get("source_tree_sha256"),
            "source_mappings_sha256": sha256(Path(str(raw_mappings))),
            "mappings": len(mappings), "total_anchors": len(plan_rows),
            "active_probes": active_count, "annotations": len(plan_rows) - active_count,
            "touched_files": touched_files,
            "diff_sha256": hashlib.sha256(diff_text.encode()).hexdigest(),
            "mechanisms": mechanisms, "isas": isas, "failures": failures,
        }
        # Auto-rebuild and wire instrumented compiler for Stage 5
        inst_artifacts = []
        rebuild_res: dict[str, Any] = {}
        try:
            from .compiler_rebuild import rebuild_instrumented_compiler
            rebuild_res = rebuild_instrumented_compiler(
                source_root=root,
                diff_path=diff_path,
                output_dir=output_dir,
                base_toolchains_config=params.get("toolchains_config"),
                compiler=mappings[0].compiler if mappings else params.get("compiler", "gcc"),
                isa=isas[0] if isas else "aarch64",
            )
            summary_record["instrumented_compiler"] = rebuild_res
            inst_toolchains_file = Path(rebuild_res["toolchains_config"])
            if inst_toolchains_file.is_file():
                inst_artifacts.append(inst_toolchains_file)
        except Exception as exc:
            failures.append(f"instrumented compiler build notice: {exc}")

        summary_path = output_dir / "instrumentation-summary.json"
        summary_path.write_text(json.dumps(summary_record, indent=2, sort_keys=True) + "\n")
        all_artifacts = (
            [diff_path, plan_path, catalog_path, summary_path, probe_header_path]
            + inst_artifacts
        )
        inst_cfg = rebuild_res.get("toolchains_config")
        return StageResult(
            stage="log-instrumentation", status=status, errors=failures,
            artifacts=[
                ArtifactRef.from_path(p, base_dir=output_dir)
                for p in all_artifacts
            ],
            metrics={"anchors": len(plan_rows), "active_probes": active_count,
                     "annotations": len(plan_rows) - active_count,
                     "touched_files": len(touched_files), "failed": len(failures)},
            metadata={"repetition": repetition, "instrumentation_diff": diff_path.name,
                      "log_id_catalog": catalog_path.name,
                      "instrumentation_summary": summary_path.name,
                      "toolchains_config": inst_cfg},
        )
    except Exception as exc:
        return StageResult(stage="log-instrumentation", status="failed",
                           error=f"{type(exc).__name__}: {exc}",
                           metadata={"repetition": repetition})


def _mechanism_by_phi(
    summary: Mapping[str, Any], params: Mapping[str, Any],
) -> dict[str, str]:
    """Resolve each mapped phi_id back to its defense mechanism.

    The accepted-invariants handoff carries the mechanism; the mapping summary
    stores the per-invariant identity hashes but not the mechanism field, so we
    read it from the frozen accepted-invariants artifact when available.
    """

    result: dict[str, str] = {}
    accepted = params.get("accepted_invariants")
    if accepted:
        path = Path(str(accepted))
        if path.is_file():
            for line in path.read_text(encoding="utf-8").splitlines():
                line = line.strip()
                if not line:
                    continue
                try:
                    record = json.loads(line)
                except json.JSONDecodeError:
                    continue
                phi = str(record.get("invariant_id") or record.get("phi_id") or "")
                mechanism = record.get("mechanism")
                if phi and mechanism:
                    result[phi] = normalize_mechanism(str(mechanism))
    return result


__all__ = ["run"]
